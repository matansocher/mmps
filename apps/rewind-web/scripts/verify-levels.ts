import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { LEVELS } from '../src/game/levels';
import { solve } from '../src/game/solver';

async function main() {
  const results = [];
  let failures = 0;
  for (const level of LEVELS) {
    try {
      const result = solve(level, 150_000);
      results.push({ id: level.id, ...result });
      console.log(
        `${String(level.id).padStart(3)} ${result.status.padEnd(10)} ${result.status === 'solved' ? String(result.actions.length).padStart(3) : '  -'} moves ${String(result.visited).padStart(6)} states  ${level.name}`,
      );
      if (result.status !== 'solved') failures++;
    } catch (error) {
      failures++;
      console.error(`${level.id}: ${error instanceof Error ? error.message : String(error)}; widths=${level.map.map((row) => row.length).join(',')}`);
    }
  }
  const proofFile = process.argv.find((argument) => argument.startsWith('--proof-file='))?.slice('--proof-file='.length);
  if (proofFile) await writeFile(proofFile, JSON.stringify(results));
  if (failures) {
    process.exitCode = 1;
    return;
  }
  if (process.argv.includes('--write-targets')) {
    const targets = results.map((result) => (result.status === 'solved' ? result.actions.length : 0));
    await writeFile(
      fileURLToPath(new URL('../src/game/level-targets.ts', import.meta.url)),
      `// Generated by scripts/verify-levels.ts from shortest paths through the production engine.\nexport const STAR_TARGETS: readonly number[] = ${JSON.stringify(targets)};\n`,
    );
  }
}

await main();
