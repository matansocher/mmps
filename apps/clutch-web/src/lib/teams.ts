function stylesFor(league: League): Record<string, TeamStyle> {
  if (league === 'ucl') return FOOTBALL_STYLES;
  if (league === 'wc' || league === 'euro') return NATIONAL_STYLES;
  return TEAM_STYLES;
}

export function teamStyle(league: League, team: string): TeamStyle {
  return stylesFor(league)[team] ?? { ...FALLBACK, abbr: team.slice(0, 3).toUpperCase() };
}

