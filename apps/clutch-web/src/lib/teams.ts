export function shortName(league: League, team: string): string {
  if (league === 'ucl') return FOOTBALL_SHORT[team] ?? team;
  if (league === 'wc' || league === 'euro') return NATIONAL_SHORT[team] ?? team;
  const parts = team.split(' ');
  return parts.length > 1 ? parts[parts.length - 1] : team;
}
