// Runtime logo URL from a public CDN, or null to signal "use the colored crest".
// A handful of defunct clubs/franchises have no CDN logo -> null triggers the crest fallback in TeamLogo.
export function logoUrl(league: League, team: string): string | null {
  if (league === 'ucl') {
    const id = UCL_ESPN_ID[team];
    return id ? `https://a.espncdn.com/i/teamlogos/soccer/500/${id}.png` : null;
  }
  if (league === 'wc' || league === 'euro') {
    const id = NATIONAL_ESPN_ID[team];
    return id ? `https://a.espncdn.com/i/teamlogos/soccer/500/${id}.png` : null;
  }
  if (BUNDLED_LOGOS[team]) return BUNDLED_LOGOS[team];
  const style = TEAM_STYLES[team];
  if (!style) return null;
  const slug = ESPN_SLUG[team] ?? style.abbr.toLowerCase();
  return `https://a.espncdn.com/i/teamlogos/nba/500/${slug}.png`;
}

